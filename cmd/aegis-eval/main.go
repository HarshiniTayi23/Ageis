// Command aegis-eval measures the ransomware detector against a labelled,
// reproducible set of scenarios: normal business changes (which must NOT be
// flagged) and attack styles (which must be), including deliberately hard
// cases. It prints a Markdown report.
//
//	go run ./cmd/aegis-eval -n 20 > docs/eval/detector-baseline.md
//
// Every scenario writes real files and measures real byte entropy, then
// scores the "after" state against the "before" state exactly as a backup
// would.
package main

import (
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"flag"
	"fmt"
	mrand "math/rand"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/HarshiniTayi23/Ageis/internal/detect"
)

type scenario struct {
	name   string
	attack bool
	hard   bool // a case we expect a rule-based detector to struggle with
	// heldOut scenarios were written BEFORE the detector was tuned and are
	// never used for tuning. They estimate how the detector does on attack
	// and business patterns it wasn't designed around.
	heldOut bool
	desc    string
	apply   func(dir string, rng *mrand.Rand)
}

func main() {
	n := flag.Int("n", 20, "runs per scenario (different seeds)")
	thr := flag.Float64("threshold", detect.Default.SuspiciousScore, "score at or above which a snapshot is flagged")
	only := flag.String("set", "all", "which scenarios: all | tuning | heldout")
	gate := flag.Bool("gate", false, "exit non-zero if quality falls below the ship bar (for CI)")
	flag.Parse()

	type result struct {
		s      scenario
		scores []float64
	}
	var results []result
	for _, s := range append(scenarios(), heldOutScenarios()...) {
		if (*only == "tuning" && s.heldOut) || (*only == "heldout" && !s.heldOut) {
			continue
		}
		r := result{s: s}
		for seed := 0; seed < *n; seed++ {
			r.scores = append(r.scores, run(s, int64(seed)))
		}
		results = append(results, r)
	}

	flagged := func(sc []float64, t float64) int {
		c := 0
		for _, x := range sc {
			if x >= t {
				c++
			}
		}
		return c
	}
	confusion := func(t float64) (tp, fn, fp, tn int) {
		for _, r := range results {
			f := flagged(r.scores, t)
			if r.s.attack {
				tp, fn = tp+f, fn+len(r.scores)-f
			} else {
				fp, tn = fp+f, tn+len(r.scores)-f
			}
		}
		return
	}

	byset := func(held bool, t float64) (tp, fn, fp, tn int) {
		for _, r := range results {
			if r.s.heldOut != held {
				continue
			}
			f := flagged(r.scores, t)
			if r.s.attack {
				tp, fn = tp+f, fn+len(r.scores)-f
			} else {
				fp, tn = fp+f, tn+len(r.scores)-f
			}
		}
		return
	}
	tp, fn, fp, tn := confusion(*thr)
	fmt.Printf("# Detector evaluation: rule-based baseline\n\n")
	fmt.Printf("Generated by `go run ./cmd/aegis-eval -n %d`. Threshold %.2f. %d scenarios × %d seeds = %d labelled snapshots.\n\n",
		*n, *thr, len(results), *n, len(results)**n)
	fmt.Printf("## Headline\n\n| | Flagged | Not flagged |\n|---|---|---|\n| **Attack** | %d (TP) | %d (FN) |\n| **Clean** | %d (FP) | %d (TN) |\n\n", tp, fn, fp, tn)
	fmt.Printf("- **Recall** (attacks caught): **%.0f%%**\n- **False-positive rate** (clean snapshots flagged): **%.0f%%**\n- **Precision** (flags that were real attacks): **%.0f%%**\n\n",
		pct(tp, tp+fn), pct(fp, fp+tn), pct(tp, tp+fp))

	fmt.Printf("| Set | Recall | False-positive rate |\n|---|---|---|\n")
	for _, held := range []bool{false, true} {
		tp, fn, fp, tn := byset(held, *thr)
		if tp+fn+fp+tn == 0 {
			continue
		}
		name := "tuning"
		if held {
			name = "held-out"
		}
		fmt.Printf("| %s | %.0f%% | %.0f%% |\n", name, pct(tp, tp+fn), pct(fp, fp+tn))
	}
	fmt.Println()

	fmt.Printf("## Per scenario\n\n| Scenario | Set | Label | Hard? | Flagged | Median score | What it is |\n|---|---|---|---|---|---|---|\n")
	for _, r := range results {
		label := "clean"
		if r.s.attack {
			label = "attack"
		}
		hard := ""
		if r.s.hard {
			hard = "yes"
		}
		f := flagged(r.scores, *thr)
		mark := ""
		if (r.s.attack && f < len(r.scores)) || (!r.s.attack && f > 0) {
			mark = " ⚠️"
		}
		set := "tuning"
		if r.s.heldOut {
			set = "**held-out**"
		}
		fmt.Printf("| %s | %s | %s | %s | %d/%d%s | %.2f | %s |\n", r.s.name, set, label, hard, f, len(r.scores), mark, median(r.scores), r.s.desc)
	}

	if *gate {
		// Ship bar from docs/pm/07-ai-eval-plan.md. Held-out recall is reported
		// but deliberately NOT gated: gating it would invite tuning against it.
		ttp, tfn, tfp, ttn := byset(false, *thr)
		_, _, hfp, htn := byset(true, *thr)
		if r, f, hf := pct(ttp, ttp+tfn), pct(tfp, tfp+ttn), pct(hfp, hfp+htn); r < 85 || f > 2 || hf > 2 {
			fmt.Fprintf(os.Stderr, "QUALITY GATE FAILED: tuning recall %.0f%% (need >= 85), tuning FPR %.0f%%, held-out FPR %.0f%% (need <= 2)\n", r, f, hf)
			defer os.Exit(1)
		}
	}

	fmt.Printf("\n## Threshold sweep\n\nMoving the threshold trades missed attacks against false alarms.\n\n| Threshold | Recall | False-positive rate | Precision |\n|---|---|---|---|\n")
	for t := 0.1; t < 0.95; t += 0.1 {
		tp, fn, fp, tn := confusion(t)
		fmt.Printf("| %.1f | %.0f%% | %.0f%% | %.0f%% |\n", t, pct(tp, tp+fn), pct(fp, fp+tn), pct(tp, tp+fp))
	}
}

func pct(a, b int) float64 {
	if b == 0 {
		return 0
	}
	return 100 * float64(a) / float64(b)
}

func median(x []float64) float64 {
	s := append([]float64(nil), x...)
	sort.Float64s(s)
	return s[len(s)/2]
}

// run builds a fresh corpus, snapshots it, applies the scenario, and scores.
func run(s scenario, seed int64) float64 {
	dir, err := os.MkdirTemp("", "aegis-eval-*")
	must(err)
	defer func() { _ = os.RemoveAll(dir) }()
	rng := mrand.New(mrand.NewSource(seed)) //nolint:gosec // G404: seeded on purpose so evaluations are reproducible
	corpus(dir, rng)
	before := snapshot(dir)
	s.apply(dir, rng)
	after := snapshot(dir)
	return detect.Analyze(before, after, detect.Default).Score
}

// corpus: a realistic-ish file share. ~75% text/CSV (low entropy) and ~25%
// already-compressed media (high entropy before any attack).
func corpus(dir string, rng *mrand.Rand) {
	words := strings.Fields("invoice patient claim amount approved pending ledger total region shipment order refund policy")
	n := 50 + rng.Intn(30)
	for i := 0; i < n; i++ {
		sub := []string{"finance", "ops", "hr", "media"}[rng.Intn(4)]
		var name string
		var data []byte
		if sub == "media" {
			name = fmt.Sprintf("photo_%03d.jpg", i)
			data = jpeg(4096 + rng.Intn(16384))
		} else {
			name = fmt.Sprintf("record_%03d.csv", i)
			var b strings.Builder
			for j := 0; j < 100+rng.Intn(300); j++ {
				fmt.Fprintf(&b, "%d,%s,%s,%d\n", j, words[rng.Intn(len(words))], words[rng.Intn(len(words))], rng.Intn(99999))
			}
			data = []byte(b.String())
		}
		p := filepath.Join(dir, sub, name)
		must(os.MkdirAll(filepath.Dir(p), 0o750))
		must(os.WriteFile(p, data, 0o600))
	}
}

func snapshot(dir string) []detect.FileStat {
	var out []detect.FileStat
	must(filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil || !d.Type().IsRegular() {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		var hist [256]uint64
		for _, c := range b {
			hist[c]++
		}
		sum := sha256.Sum256(b)
		rel, _ := filepath.Rel(dir, p)
		head := b
		if len(head) > 512 {
			head = head[:512]
		}
		out = append(out, detect.FileStat{Path: filepath.ToSlash(rel), SHA256: hex.EncodeToString(sum[:]),
			Size: int64(len(b)), Entropy: detect.Entropy(&hist, uint64(len(b))), Type: detect.Sniff(head)})
		return nil
	}))
	return out
}

// ---------------------------------------------------------------- helpers ---

func files(dir string, filter func(string) bool) []string {
	var out []string
	_ = filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err == nil && d.Type().IsRegular() && (filter == nil || filter(p)) {
			out = append(out, p)
		}
		return nil
	})
	sort.Strings(out)
	return out
}

func pick(rng *mrand.Rand, xs []string, frac float64) []string {
	rng.Shuffle(len(xs), func(i, j int) { xs[i], xs[j] = xs[j], xs[i] })
	k := int(frac * float64(len(xs)))
	if k < 1 && frac > 0 {
		k = 1
	}
	return xs[:k]
}

func isText(p string) bool  { return strings.HasSuffix(p, ".csv") || strings.HasSuffix(p, ".txt") }
func isMedia(p string) bool { return strings.HasSuffix(p, ".jpg") }

func randBytes(n int) []byte {
	b := make([]byte, n)
	_, _ = rand.Read(b)
	return b
}

// jpeg returns n bytes that look like a JPEG: the real file signature and
// header, then high-entropy compressed-looking data.
func jpeg(n int) []byte {
	b := randBytes(n)
	copy(b, []byte("\xFF\xD8\xFF\xE0\x00\x10JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"))
	return b
}

func size(p string) int {
	fi, err := os.Stat(p)
	must(err)
	return int(fi.Size())
}

func encrypt(p string) { must(os.WriteFile(p, randBytes(size(p)), 0o600)) }
func appendText(p, s string) {
	f, err := os.OpenFile(p, os.O_APPEND|os.O_WRONLY, 0)
	must(err)
	_, _ = f.WriteString(s)
	_ = f.Close()
}
func renameTo(p, suffix string) { must(os.Rename(p, p+suffix)) }
func note(dir, name string)     { must(os.WriteFile(filepath.Join(dir, name), []byte("pay 5 BTC"), 0o600)) }
func remove(p string)           { must(os.Remove(p)) }
func writeNew(p string, b []byte) {
	must(os.MkdirAll(filepath.Dir(p), 0o750))
	must(os.WriteFile(p, b, 0o600))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

// -------------------------------------------------------------- scenarios ---

// heldOutScenarios were written before any detector tuning (see
// docs/eval/README.md). Do not tune against them.
func heldOutScenarios() []scenario {
	all := func(dir string) []string { return files(dir, nil) }
	text := func(dir string) []string { return files(dir, isText) }
	return []scenario{
		{name: "bulk .bak copies", heldOut: true, desc: "admin renames 50% of files to name.bak (content unchanged)", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.5) {
				renameTo(p, ".bak")
			}
		}},
		{name: "database dump replaced", heldOut: true, desc: "one big CSV rewritten entirely with new rows", apply: func(d string, r *mrand.Rand) {
			ts := text(d)
			p := ts[r.Intn(len(ts))]
			must(os.WriteFile(p, []byte(strings.Repeat("id,new,export,2026\n", 2000)), 0o600))
		}},
		{name: "half the share deleted by retention policy", heldOut: true, desc: "55% of files deleted on schedule", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.55) {
				remove(p)
			}
		}},
		{name: "quiet ransomware", attack: true, heldOut: true, desc: "40% encrypted and renamed .encrypted, no note", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.4) {
				encrypt(p)
				renameTo(p, ".encrypted")
			}
		}},
		{name: "XOR 'encryption'", attack: true, hard: true, heldOut: true, desc: "60% XORed with a 1-byte key (cheap ransomware; entropy unchanged)", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.6) {
				b, _ := os.ReadFile(p)
				for i := range b {
					b[i] ^= 0x5A
				}
				must(os.WriteFile(p, b, 0o600))
			}
		}},
		{name: "encrypt + new folder", attack: true, heldOut: true, desc: "75% encrypted and moved into a new folder 'locked/'", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.75) {
				encrypt(p)
				np := filepath.Join(d, "locked", filepath.Base(p))
				must(os.MkdirAll(filepath.Dir(np), 0o750))
				must(os.Rename(p, np))
			}
		}},
	}
}

func scenarios() []scenario {
	all := func(dir string) []string { return files(dir, nil) }
	text := func(dir string) []string { return files(dir, isText) }
	media := func(dir string) []string { return files(dir, isMedia) }
	return []scenario{
		// --- normal business: must NOT be flagged
		{name: "small edits", desc: "a few CSVs get new rows", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, text(d), 0.05) {
				appendText(p, "999,late,entry,1\n")
			}
		}},
		{name: "month-end bulk edit", desc: "every CSV gets a new column", apply: func(d string, r *mrand.Rand) {
			for _, p := range text(d) {
				b, _ := os.ReadFile(p)
				must(os.WriteFile(p, []byte(strings.ReplaceAll(string(b), "\n", ",closed\n")), 0o600))
			}
		}},
		{name: "folder reorganisation", desc: "half the files moved to new folders", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.5) {
				np := filepath.Join(d, "archive-2026", filepath.Base(p))
				must(os.MkdirAll(filepath.Dir(np), 0o750))
				must(os.Rename(p, np))
			}
		}},
		{name: "new project imported", desc: "many new files appear", apply: func(d string, r *mrand.Rand) {
			for i := 0; i < 60; i++ {
				writeNew(filepath.Join(d, "newproj", fmt.Sprintf("n%d.csv", i)), []byte(strings.Repeat("a,b,c\n", 100)))
			}
		}},
		{name: "cleanup deletes", desc: "40% of old files deleted", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.4) {
				remove(p)
			}
		}},
		{name: "photos re-exported", desc: "all media files re-encoded (new content, still valid JPEGs)", apply: func(d string, r *mrand.Rand) {
			for _, p := range media(d) {
				must(os.WriteFile(p, jpeg(size(p)), 0o600))
			}
		}},
		{name: "user zips old records", hard: true, desc: "60% of CSVs compressed into .zip and originals removed (legitimately high entropy)", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, text(d), 0.6) {
				writeNew(strings.TrimSuffix(p, ".csv")+".zip", randBytes(size(p)/3+64))
				remove(p)
			}
		}},
		{name: "password-protected export", hard: true, desc: "30% of CSVs encrypted in place by a legitimate tool, names kept", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, text(d), 0.3) {
				encrypt(p)
			}
		}},

		// --- attacks: must be flagged
		{name: "classic ransomware", attack: true, desc: "80% encrypted, renamed .locked, ransom note", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.8) {
				encrypt(p)
				renameTo(p, ".locked")
			}
			note(d, "HOW_TO_DECRYPT.txt")
		}},
		{name: "in-place encryption", attack: true, desc: "50% encrypted, names kept, no note", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.5) {
				encrypt(p)
			}
		}},
		{name: "unknown extension", attack: true, desc: "70% encrypted and renamed to a random extension (.x7k2q)", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.7) {
				encrypt(p)
				renameTo(p, ".x7k2q")
			}
		}},
		{name: "wiper", attack: true, desc: "90% of files deleted, nothing encrypted", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.9) {
				remove(p)
			}
		}},
		{name: "slow encryption", attack: true, hard: true, desc: "only 10% encrypted before this backup (attack spread over days)", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.1) {
				encrypt(p)
			}
		}},
		{name: "intermittent encryption", attack: true, hard: true, desc: "first 4 KiB of 70% of files encrypted (LockBit-style speed trick)", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.7) {
				b, _ := os.ReadFile(p)
				k := 4096
				if k > len(b) {
					k = len(b)
				}
				copy(b, randBytes(k))
				must(os.WriteFile(p, b, 0o600))
			}
		}},
		{name: "base64-encoded ciphertext", attack: true, hard: true, desc: "60% encrypted then base64-encoded, so entropy is ~6 bits/byte, not ~8", apply: func(d string, r *mrand.Rand) {
			for _, p := range pick(r, all(d), 0.6) {
				must(os.WriteFile(p, []byte(base64.StdEncoding.EncodeToString(randBytes(size(p)))), 0o600))
			}
		}},
		{name: "media-only encryption", attack: true, hard: true, desc: "only already-compressed files encrypted: no entropy jump to see", apply: func(d string, r *mrand.Rand) {
			for _, p := range media(d) {
				encrypt(p)
			}
		}},
	}
}
